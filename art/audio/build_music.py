#!/usr/bin/env python3
"""The licensed music beds the owner picked from docs/audio/music_demo.ogg, cut into seamless loops.

Each pick is downloaded (same sources as build_music_demo.py, CC-BY 4.0), loudness-matched to -20 LUFS integrated
(linear gain, measured with ffmpeg's EBU R128 filter, true peak kept under -1 dBTP), and made loopable: the last
LOOP_XFADE seconds are crossfaded (equal power) with the first ones and the loop starts after that overlap, so the
end flows into the start without a seam. Writes game/public/assets/audio/<name>.ogg (Opus, stereo) and
game/src/audio/music-manifest.js (merged into the sound manifest by src/audio/audio.js).

Usage: python3 art/audio/build_music.py
"""
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from scipy.io import wavfile

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_music_demo import fetch, km, sb  # noqa: E402  (same sources and credit lines as the demo)

SR = 48000
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "game/public/assets/audio"
MANIFEST = ROOT / "game/src/audio/music-manifest.js"
LOOP_XFADE = 6.0
TARGET_LUFS = -20.0
BITRATE = "64k"

# name -> source; the owner's picks (12.11). The town theme is one of the two mus_town_* (src/audio/music.js).
PICKS = {
    "mus_interior": sb("Tears in Rain", "2019/07/sb_tearsinrain.mp3"),
    "mus_town_moonlight": sb("Moonlight", "2022/07/Moonlight.mp3"),
    "mus_town_dreams": km("Dreams Become Real"),
}


def decode(path):
    r = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "2", "-ar", str(SR), "-f", "f32le", "-"],
                       capture_output=True, check=True)
    return np.frombuffer(r.stdout, np.float32).astype(np.float64).reshape(-1, 2)


def loudness(path):
    r = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(path), "-af", "loudnorm=print_format=json", "-f", "null", "-"],
                       capture_output=True, text=True)
    m = json.loads(re.search(r"\{[^{}]*\"input_i\"[^{}]*\}", r.stderr, re.S).group(0))
    return float(m["input_i"])


def seamless(x, xf):
    """Loop body x[n:] whose tail is crossfaded (equal power) with x[:n]: playing it on repeat has no seam."""
    n = int(xf * SR)
    t = np.linspace(0, np.pi / 2, n)[:, None]
    y = x[n:].copy()
    y[-n:] = y[-n:] * np.cos(t) + x[:n] * np.sin(t)
    return y


def encode(y, out):
    with tempfile.TemporaryDirectory() as td:
        wav = Path(td) / "m.wav"
        wavfile.write(wav, SR, y.astype(np.float32))
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(wav), "-c:a", "libopus", "-b:a", BITRATE,
                        "-vbr", "on", "-compression_level", "10", "-application", "audio", "-map_metadata", "-1",
                        "-fflags", "+bitexact", "-flags:a", "+bitexact", str(out)], check=True)


def main():
    entries = {}
    for name, src in PICKS.items():
        path = fetch(src)
        x = decode(path)
        # trim the silent head and tail so the loop has no gap
        a = np.max(np.abs(x), axis=1)
        nz = np.nonzero(a > 10 ** (-50 / 20))[0]
        x = x[nz[0]: nz[-1] + 1]
        x *= 10 ** ((TARGET_LUFS - loudness(path)) / 20)
        y = seamless(x, LOOP_XFADE)
        pk = np.max(np.abs(y))
        if pk > 10 ** (-1 / 20):
            y *= 10 ** (-1 / 20) / pk
        encode(y, OUT / f"{name}.ogg")
        entries[name] = {"file": f"{name}.ogg", "kind": "music", "dur": round(len(y) / SR, 4), "samples": len(y),
                         "channels": 2, "loop": True, "title": src["title"], "artist": src["artist"],
                         "licence": src["licence"], "source": src["url"], "credit": src["credit"]}
        print(f"{name}: {src['title']} {len(y) / SR:.1f} s", file=sys.stderr)
    body = json.dumps({"sounds": entries}, indent=2)
    MANIFEST.write_text("// Generated by art/audio/build_music.py: the licensed music beds (CC-BY 4.0, credited in\n"
                        "// docs/art/manifest.md and the README). Do not edit by hand.\n"
                        f"export const MUSIC_MANIFEST = {body};\n")


if __name__ == "__main__":
    main()
