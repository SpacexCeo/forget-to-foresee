"""samples.py <pack dir> <out dir> <manifest.js>: the recorded sounds that replace the weakest synthesized ones.

The owner (14.11): rework the game's sounds with an open-source engine and real recordings where the synth is weak.
Source: Kenney's RPG Audio and Interface Sounds packs (CC0, kenney.nl; mirrored on opengameart.org), unpacked in
<pack dir>/rpg and <pack dir>/interface. Each replacement is matched in loudness to the synthesized sound it replaces
(the RMS level of the old file, never above -1 dBFS peak), trimmed of silence, made mono 48 kHz and encoded as Ogg Opus like the
rest; the files are named `k_<old name>.ogg` and the overlay manifest (game/src/audio/sample-manifest.js) points the
old names at them, so the synthesized originals stay as they are (art/audio/build_audio.py) and the game code that
plays `step_stone` or `ui_click` does not change.
"""
import json
import os
import re
import subprocess
import sys

PACK, OUT, MANIFEST = sys.argv[1], sys.argv[2], sys.argv[3]
ORIG = os.path.join(os.path.dirname(MANIFEST), "..", "..", "public", "assets", "audio")

# old name -> (pack file, extra ffmpeg filter)
MAP = {
    **{f"step_wood_{i + 1}": (f"rpg/footstep0{i}.ogg", "") for i in range(6)},
    # stone: the same steps, brighter and drier (less low body, a touch of grit), so plaza and wood differ
    **{f"step_stone_{i + 1}": (f"rpg/footstep0{i + 4}.ogg", "highpass=f=160,equalizer=f=3500:t=q:w=1:g=4,asetrate=48000*1.06,aresample=48000") for i in range(6)},
    "strike_swing_1": ("rpg/knifeSlice.ogg", ""),
    "strike_swing_2": ("rpg/knifeSlice2.ogg", ""),
    "strike_swing_3": ("rpg/drawKnife1.ogg", ""),
    "strike_swing_4": ("rpg/drawKnife2.ogg", ""),
    "ui_click": ("interface/click_002.ogg", ""),
    "ui_hover": ("interface/tick_001.ogg", ""),
    "ui_confirm": ("interface/confirmation_002.ogg", ""),
    "ui_error": ("interface/error_004.ogg", ""),
    "ui_notify": ("interface/maximize_006.ogg", ""),
}


def find(rel):
    d, name = os.path.split(rel)
    for root, _, files in os.walk(os.path.join(PACK, d)):
        if name in files:
            return os.path.join(root, name)
    raise SystemExit("missing " + rel)


def loudness(path):
    """RMS and peak (dBFS) over the whole file: these are short one-shots, below the 400 ms gate of EBU R128."""
    r = subprocess.run(["ffmpeg", "-nostdin", "-hide_banner", "-i", path, "-af", "astats=measure_perchannel=none", "-f", "null", "-"], capture_output=True, text=True).stderr
    rms = re.findall(r"RMS level dB:\s+(-?[\d.]+|-inf)", r)
    pk = re.findall(r"Peak level dB:\s+(-?[\d.]+|-inf)", r)
    f = lambda v: -90.0 if v == "-inf" else float(v)
    return f(rms[-1]), f(pk[-1])


os.makedirs(OUT, exist_ok=True)
overlay = {}
for old, (rel, extra) in MAP.items():
    src = find(rel)
    target, _ = loudness(os.path.join(ORIG, old + ".ogg"))
    target = max(-45.0, min(-8.0, target))
    tmp = os.path.join(OUT, "_" + old + ".wav")
    chain = ",".join(x for x in ["aformat=channel_layouts=mono", "aresample=48000", extra,
                                 "silenceremove=start_periods=1:start_threshold=-55dB",
                                 "areverse,silenceremove=start_periods=1:start_threshold=-60dB,areverse"] if x)
    subprocess.run(["ffmpeg", "-nostdin", "-y", "-loglevel", "error", "-i", src, "-af", chain, tmp], check=True)
    cur, peak = loudness(tmp)
    gain = min(target - cur, -1.0 - peak)          # match the old loudness, never above -1 dBFS peak
    dst = os.path.join(OUT, "k_" + old + ".ogg")
    subprocess.run(["ffmpeg", "-nostdin", "-y", "-loglevel", "error", "-i", tmp, "-af", f"volume={gain:.2f}dB", "-c:a", "libopus", "-b:a", "64k", "-ar", "48000", dst], check=True)
    dur = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", dst], capture_output=True, text=True).stdout.strip())
    os.remove(tmp)
    overlay[old] = {"file": "k_" + old + ".ogg", "dur": round(dur, 3), "source": "Kenney " + ("RPG Audio" if rel.startswith("rpg") else "Interface Sounds") + " (CC0): " + os.path.basename(rel)}
    print(f"[samples] {old:16s} <- {rel:28s} {cur:6.1f} -> {target:6.1f} dB RMS, {dur:.2f} s")

with open(MANIFEST, "w") as f:
    f.write("// GENERATED by art/audio/samples.py; do not edit by hand. The recorded sounds (CC0, Kenney) that replace the weakest\n"
            "// synthesized ones: each entry overrides the file of the synthesized sound of the same name (audio.js withSamples).\n"
            "export const SAMPLE_OVERRIDES = " + json.dumps(overlay, indent=2) + ";\n")
print("[samples] wrote", MANIFEST, len(overlay))
