// grip_rigs_js.mjs: writes game/src/play/grip-pose-rigs.js from the JSON files of art/agents/grip_fit_rig.mjs.
//   node art/agents/grip_rigs_js.mjs <out.js> <iris.grip.json> [<elise.grip.json> ...]
import { readFileSync, writeFileSync } from 'node:fs';

const [OUT, ...files] = process.argv.slice(2);
const grips = files.map((f) => { const j = JSON.parse(readFileSync(f, 'utf8')); return { rig: j.rig, seat: j.seat, sword_in_seat: j.sword_in_seat, pose: j.pose, fit: { gap_mm: j.gap_mm, near: j.vertices_near_the_hilt } }; });
const body = `// Loomblade grips for the heroines' other rigs (3D A, 14.11): the new Tripo Iris (R_Hand, R_Index1..3, R_Thumb1..3) and
// Elise (Mixamo, mixamorigRightHand...) have no \`prop_R\` socket, so play/grip-pose.js (the game's own rig) does not fit
// them. Each entry: {rig, seat: the bone the sword hangs on, sword_in_seat: column-major 4x4 in that bone's space,
// pose: {bone: [x, y, z, w]} local quaternions of the closed fingers}. Generated by art/agents/grip_rigs_js.mjs from
// art/agents/grip_fit_rig.mjs (the owner's photo grip: the hilt diagonal across the palm, every finger closed on it).
// Do not edit by hand.
export const GRIPS = Object.freeze(${JSON.stringify(grips, (k, v) => (Array.isArray(v) && v.every(Number.isFinite) ? '@@' + v.join(', ') + '@@' : v), 1).replace(/"@@(.*?)@@"/g, '[$1]')});
`;
writeFileSync(OUT, body);
console.log('wrote', OUT, grips.map((g) => g.rig + ':' + Object.keys(g.pose).length).join(' '));
