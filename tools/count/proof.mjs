// Writes docs/proof/tx-<day>.md (and docs/proof/tx-24h.md, the latest) from a count.mjs result. Deterministic for a
// given chain state and window, so a rerun overwrites the same file; rerun after the day ends for the final number.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { INDEXER, EXPLORER, ACCOUNTS } from './count.mjs';
import { runway } from './runway.mjs';

const fmt = (n) => n.toLocaleString('en');
function table(title, head, m, link) {
  const rows = Object.entries(m).sort((a, b) => (b[1].ok + b[1].failed) - (a[1].ok + a[1].failed));
  return [`### ${title}`, '', `| ${head} | Successful | Failed |`, '| --- | ---: | ---: |',
    ...rows.map(([k, v]) => `| ${link ? link(k) : k} | ${fmt(v.ok)} | ${fmt(v.failed)} |`)].join('\n');
}
const acct = (a) => `[${a}](${EXPLORER}/address/${a})`;

export function proofMarkdown(r, { now = Date.now(), runwayMd = null } = {}) {
  const day = r.window.from.slice(0, 10);
  const complete = Date.parse(r.window.to) <= now;
  const hours = (Math.min(now, Date.parse(r.window.to)) - Date.parse(r.window.from)) / 3600e3;
  return [
    `# Testnet transactions, ${day} (UTC)`, '',
    complete ? `**Final count for the full UTC day.**` : `**Partial: the window is still open.** Counted up to ${new Date(now).toISOString().slice(0, 16)} UTC (${hours.toFixed(1)} h of 24). Rerun after 00:00 UTC for the final number.`, '',
    `Generated by \`node tools/count/count.mjs --window ${day} --write\` from the public NearBlocks indexer (${INDEXER}). No keys; every number below can be recounted.`, '',
    '| | |', '| --- | ---: |',
    `| Successful transactions | **${fmt(r.ok)}** |`, `| Failed transactions | ${fmt(r.failed)} |`, `| All transactions | ${fmt(r.total)} |`,
    `| Distinct signing accounts | ${fmt(r.distinctSigners)} |`, `| Market trades (\`ftf-town.testnet : trade\`) | ${fmt((r.byMethod['ftf-town.testnet:trade'] || { ok: 0 }).ok)} |`, '',
    table('By contract (receiver)', 'Contract', r.byReceiver, acct), '',
    table('Method mix', 'Contract : method', r.byMethod, (k) => { const [c, m] = k.split(':'); return `${acct(c)} : \`${m}\``; }), '',
    table('By signing account', 'Signer', r.bySigner, acct), '',
    `### Failures (${r.failures.length})`, '',
    ...(r.failures.length ? r.failures.slice(0, 100).map((f) => `- [${f.hash}](${f.url}) ${f.signer} → ${f.receiver} \`${f.method}\``) : ['None.']), '',
    '## How to verify it yourself', '',
    `1. Recount: \`git clone\` this repository and run \`node tools/count/count.mjs --window ${day}\` (Node 18+, no install, no keys). It pages ${INDEXER}/accounts/<contract>/txns for ${ACCOUNTS.length} contracts and de-duplicates by hash.`,
    `2. Spot-check any transaction: open ${EXPLORER}/txns/<hash>, or ask a node directly: \`curl -s https://test.rpc.fastnear.com -H 'Content-Type: application/json' -d '{"jsonrpc":"2.0","id":1,"method":"tx","params":{"tx_hash":"<hash>","sender_account_id":"<signer>","wait_until":"FINAL"}}'\`.`,
    `3. Compare with the contract's own counter: \`trade\` in \`pulse {}\` on ftf-town.testnet (docs/stats-page.md) grows by the trade count above.`,
    `4. Browse an account's history: ${EXPLORER}/address/ftf-town.testnet.`, '',
    ...(runwayMd ? ['## Gas runway', '', 'From `node tools/count/runway.mjs` (read only). Used for top-ups.', '', runwayMd, ''] : []),
  ].join('\n');
}

export async function writeProof(r, { now = Date.now() } = {}) {
  let runwayMd = null;
  try { runwayMd = await runway({ hours: 1 }); } catch { runwayMd = 'Runway unavailable: the RPC or indexer did not answer.'; }
  const md = proofMarkdown(r, { now, runwayMd });
  const dir = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'docs', 'proof');
  mkdirSync(dir, { recursive: true });
  const day = r.window.from.slice(0, 10);
  writeFileSync(join(dir, `tx-${day}.md`), md);
  writeFileSync(join(dir, 'tx-24h.md'), md);
  return join('docs/proof', `tx-${day}.md`) + ' and docs/proof/tx-24h.md';
}
