export function buildVectors() {
  const shards = CASES.map((input) => {
    const data = shardData(input);
    const svg = shardSvg(data);
    const m = shardMetadata(data);
    return { input, tokenId: shardTokenId(data), svg, svgSha256: sha256(svg), metadata: m };
  });
  for (const bad of INVALID) { let threw = false; try { shardData(bad.data); } catch { threw = true; } if (!threw) throw new Error('invalid case accepted: ' + bad.why); }
  return {
    about: 'Generated by game/scripts/gen-shard-vectors.mjs from src/net/shard-nft.js. Do not edit by hand.',
    spec: 'ftf-shard/1',
    image: 'ink ring 320x320: 8 strokes from the first 16 nibbles of unlocked_leaf (or schedule_root), weight dots, a full core when bought, hollow when burned; DIRS = cos/sin x 1000 of 16 directions; integer math only',
    shards,
    invalid: INVALID,
  };
}
export const serialize = (v) => JSON.stringify(v, null, 1) + '\n';

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const v = buildVectors();
  writeFileSync(OUT, serialize(v));
  console.log(`wrote ${OUT}: ${v.shards.length} shards, ${v.invalid.length} invalid cases`);
}
