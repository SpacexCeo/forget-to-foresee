// Builds the sealed Foresight Exchange snapshot (Judge Echo, docs/agent-market-plan.md Scope A): a fixed range of
// European Central Bank reference rates via Frankfurter, USD base, EUR / JPY / CHF. Run once by hand; the game and
// the tests only read the committed files and never fetch. A re-run must reproduce the committed hash.
//   node scripts/build-exchange-snapshot.mjs
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { sha256 } from '../src/game/crypto.js';
import { canonicalSnapshotPayload } from '../src/game/exchange.js';

const FROM = '2024-01-02', TO = '2024-02-29';
const URL_ = `https://api.frankfurter.dev/v1/${FROM}..${TO}?base=USD&symbols=EUR,JPY,CHF`;
const res = await fetch(URL_);
if (!res.ok) throw new Error('fetch failed: ' + res.status);
const j = await res.json();
const quotes = ['EUR', 'JPY', 'CHF'];
const bars = Object.keys(j.rates).sort().map((t) => ({ t, EUR: j.rates[t].EUR, JPY: j.rates[t].JPY, CHF: j.rates[t].CHF }));
const snap = {
  spec: 'ftf-exchange-snapshot/1',
  id: 'echo-2024-q1',
  source: 'https://api.frankfurter.dev (Frankfurter)',
  attribution: 'European Central Bank euro foreign exchange reference rates via Frankfurter (frankfurter.dev); reuse of ECB data is free with attribution of the source.',
  range: [FROM, TO],
  retrievedAt: new Date().toISOString(),
  base: 'USD',
  quotes,
  bars,
};
snap.hash = sha256(canonicalSnapshotPayload(snap));
const jsPath = new URL('../src/game/exchange/snapshot-v1.js', import.meta.url);
if (existsSync(jsPath)) {
  const prev = readFileSync(jsPath, 'utf8').match(/"hash": "([0-9a-f]{64})"/);
  if (prev && prev[1] !== snap.hash) throw new Error(`hash changed: committed ${prev[1]}, fetched ${snap.hash}`);
  if (prev) snap.retrievedAt = JSON.parse(readFileSync(new URL('../public/data/exchange-snapshot-v1.json', import.meta.url), 'utf8')).retrievedAt;
}
const json = JSON.stringify(snap, null, 2);
writeFileSync(new URL('../public/data/exchange-snapshot-v1.json', import.meta.url), json + '\n');
writeFileSync(jsPath, '// Generated by scripts/build-exchange-snapshot.mjs (do not edit). The same data as public/data/exchange-snapshot-v1.json.\nexport default ' + json + ';\n');
console.log(snap.id, bars.length, 'bars', snap.hash);
