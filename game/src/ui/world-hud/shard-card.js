// Shard NFT card and the "Minted on NEAR testnet" toast (DOM). The view model is shard-card-model.js; this file only
// draws it. The ink ring is the contract's own SVG (verified byte-identical to the game's shardSvg before it is drawn
// inline), and its strokes draw themselves in (stroke-dashoffset, motion tokens; reduced motion: a short fade).
import { ensureWhStyle } from './index.js';

const SVG_NS = 'http://www.w3.org/2000/svg';

function el(doc, tag, attrs = {}, ...kids) {
  const e = doc.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (v == null || v === false) continue;
    if (k === 'text') e.textContent = v;
    else if (k === 'class') e.className = v;
    else if (k.startsWith('on')) e.addEventListener(k.slice(2), v);
    else e.setAttribute(k, v === true ? '' : v);
  }
  for (const c of kids.flat()) if (c != null) e.append(c);
  return e;
}

const link = (doc, href, text, cls) => (href
  ? el(doc, 'a', { class: cls, href, target: '_blank', rel: 'noopener noreferrer', text })
  : el(doc, 'span', { class: cls, text }));

export function ensureShardCardStyle(doc = document) {
  ensureWhStyle('shard-card', new URL('./shard-card.css', import.meta.url).href, doc);
}

/**
 * The ink ring. A verified SVG (generated by the game from the token's on-chain data, equal to the chain's bytes) is
 * parsed into the DOM so its strokes can animate; an unverified one is shown as an <img> of the chain's media.
 */
export function shardImage(doc, card, size = 132) {
  const box = el(doc, 'div', { class: 'sh-ink', style: `--sh-size:${size}px` });
  if (card.svg && typeof DOMParser !== 'undefined') {
    const parsed = new DOMParser().parseFromString(card.svg, 'image/svg+xml').documentElement;
    if (parsed && parsed.namespaceURI === SVG_NS) {
      const svg = doc.importNode(parsed, true);
      svg.removeAttribute('width'); svg.removeAttribute('height');
      svg.setAttribute('role', 'img');
      svg.setAttribute('aria-label', card.tokenId);
      let i = 0;
      for (const s of svg.querySelectorAll('circle, line')) {
        s.setAttribute('pathLength', '1');
        s.style.setProperty('--sh-i', String(i++));
      }
      box.append(svg);
      setTimeout(() => box.classList.add('sh-drawn'), 2000); // see .sh-drawn in shard-card.css
      return box;
    }
  }
  if (card.media) box.append(el(doc, 'img', { src: card.media, alt: card.tokenId, width: size, height: size }));
  return box;
}

/** A full card: image, the NFT line, token id and owner, the biography, the season binding, links. */
export function renderShardCard(card, { t, doc = document } = {}) {
  const clan = (c) => t('agent.' + c);
  const kind = t('shard.nft.kind.' + card.kind);
  const bio = card.weight > 0
    ? t('shard.nft.bio', { clan: clan(card.ownerClan), kind, weight: card.weight, trial: card.forgottenAt })
    : t('shard.nft.bio0', { clan: clan(card.ownerClan), kind, trial: card.forgottenAt });
  const sale = card.winner
    ? t('shard.nft.sold', { clan: clan(card.winner), price: card.price ?? 0, trial: card.closesAt })
    : t('shard.nft.burned', { trial: card.closesAt });
  const node = el(doc, 'article', { class: 'sh-card', 'data-token': card.tokenId },
    shardImage(doc, card),
    el(doc, 'div', { class: 'sh-body' },
      el(doc, 'p', { class: 'sh-kicker', text: `NFT · ${card.standard} · ${card.contractId}` }),
      el(doc, 'h4', { class: 'sh-title', text: t('shard.nft.title', { id: card.shardId, kind }) }),
      el(doc, 'dl', { class: 'sh-facts' },
        el(doc, 'dt', { text: t('shard.nft.token') }), el(doc, 'dd', { class: 'sh-mono', text: card.tokenId }),
        card.owner ? [el(doc, 'dt', { text: t('shard.nft.owner') }), el(doc, 'dd', {}, link(doc, card.ownerHref, card.owner, 'sh-mono'))] : null),
      el(doc, 'p', { class: 'sh-bio', text: bio + ' ' + sale }),
      card.leaf ? el(doc, 'p', { class: 'sh-seal' }, link(doc, card.leaf.href, t('shard.nft.leaf', { index: card.leaf.index }), 'sh-seal__link')) : null,
      el(doc, 'p', { class: 'sh-links' },
        link(doc, card.tokenHref, t('shard.nft.view'), 'sh-btn'),
        card.svgVerified ? el(doc, 'span', { class: 'sh-verified', text: t('shard.nft.verified') }) : null)));
  setTimeout(() => node.classList.add('sh-drawn'), 2000);
  return node;
}

/** The Memories panel section: heading + cards, or the quiet "judge season only" line. */
export function renderShardSection({ cards, judgeOnly }, { t, doc = document } = {}) {
  if (!cards.length && !judgeOnly) return null;
  ensureShardCardStyle(doc);
  if (!cards.length) return el(doc, 'p', { class: 'sh-note', text: t('shard.nft.judgeOnly') });
  return el(doc, 'section', { class: 'sh-section', 'aria-label': t('shard.nft.heading') },
    el(doc, 'h3', { text: t('shard.nft.heading') }),
    cards.map(({ card }) => renderShardCard(card, { t, doc })));
}

/**
 * The mint toast: a small card that slides in, draws the ring, and leaves after `ttl` ms (or on close).
 * `show(card)` queues; one toast at a time.
 */
export function createMintToast(host, { t, doc = host.ownerDocument || document, ttl = 9000, onOpen = null } = {}) {
  ensureShardCardStyle(doc);
  const region = el(doc, 'div', { class: 'sh-toast-region', role: 'status', 'aria-live': 'polite' });
  host.append(region);
  const queue = [];
  let current = null, timer = 0;
  function next() {
    if (current || !queue.length) return;
    const card = queue.shift();
    const close = () => {
      if (!current) return;
      clearTimeout(timer);
      const node = current; current = null;
      node.classList.add('sh-toast--out');
      setTimeout(() => { node.remove(); next(); }, 260);
    };
    const kind = t('shard.nft.kind.' + card.kind);
    current = el(doc, 'div', { class: 'sh-toast', 'data-token': card.tokenId },
      shardImage(doc, card, 56),
      el(doc, 'div', { class: 'sh-toast__body' },
        el(doc, 'p', { class: 'sh-toast__title', text: t('shard.nft.minted') }),
        el(doc, 'p', { class: 'sh-toast__text', text: t('shard.nft.toast', { id: card.shardId, kind, clan: t('agent.' + card.winner), price: card.price ?? 0 }) }),
        el(doc, 'p', { class: 'sh-toast__links' },
          el(doc, 'span', { class: 'sh-mono', text: card.tokenId }),
          link(doc, card.tokenHref, t('shard.nft.view'), 'sh-toast__link'),
          onOpen ? el(doc, 'button', { class: 'sh-toast__link', type: 'button', text: t('shard.nft.open'), onclick: () => { close(); onOpen(card); } }) : null)),
      el(doc, 'button', { class: 'sh-toast__close', type: 'button', 'aria-label': t('shard.nft.close'), text: '×', onclick: close }));
    region.append(current);
    timer = setTimeout(close, ttl);
  }
  return {
    show(card) { queue.push(card); next(); },
    get visible() { return !!current; },
    destroy() { clearTimeout(timer); region.remove(); },
  };
}
