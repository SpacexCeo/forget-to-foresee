export const SHOAL_TEXT = Object.freeze({ en, ru, uk, it, zh });
/** The text for a key in a locale (English when missing), with {name} arguments filled in. */
export function shoalText(locale, key, args = {}) {
  const loc = SHOAL_TEXT[String(locale || 'en').slice(0, 2)] || en;
  const s = loc[key] || en[key] || key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (args[k] != null ? String(args[k]) : ''));
}
