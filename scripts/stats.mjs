#!/usr/bin/env node
// One source of truth for the numbers the README quotes (audit QW-12, QW-7): runs every test suite, counts passes,
// measures the production build if it exists, and with --write records docs/STATS.md and docs/stats.json with the
// date and git commit. Exit code 1 when any suite fails.
//   node scripts/stats.mjs [--skip-rust] [--write]
import { spawnSync, execSync } from 'node:child_process';
import { existsSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));
export const CONTRACTS = ['season-commit', 'memory-shard', 'agent-card', 'guests', 'character-nft', 'token-account'];

/** Parses `node --test` or `cargo test` output into {pass, fail}. */
export function parseCounts(out) {
  const node = { pass: /^# pass (\d+)/m.exec(out), fail: /^# fail (\d+)/m.exec(out) };
  if (node.pass) return { pass: +node.pass[1], fail: node.fail ? +node.fail[1] : 0 };
  let pass = 0, fail = 0, seen = false;
  for (const m of out.matchAll(/^test result: \w+\. (\d+) passed; (\d+) failed/gm)) { pass += +m[1]; fail += +m[2]; seen = true; }
  return seen ? { pass, fail } : null;
}

function run(name, cwd, cmd, cmdArgs) {
  const t0 = Date.now();
  const r = spawnSync(cmd, cmdArgs, { cwd: join(ROOT, cwd), encoding: 'utf8', maxBuffer: 64 << 20 });
  const out = (r.stdout || '') + (r.stderr || '');
  const c = parseCounts(out);
  const ok = r.status === 0 && c && c.fail === 0;
  return { name, command: `cd ${cwd} && ${cmd} ${cmdArgs.join(' ')}`, pass: c ? c.pass : 0, fail: c ? c.fail : null, ok, seconds: Math.round((Date.now() - t0) / 100) / 10 };
}

function dirSize(p) {
  if (!existsSync(p)) return null;
  let n = 0;
  for (const e of readdirSync(p, { withFileTypes: true })) { const f = join(p, e.name); n += e.isDirectory() ? dirSize(f) : statSync(f).size; }
  return n;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const rows = [run('game', 'game', 'npm', ['test']), run('server', 'server', 'npm', ['test']), run('relayer', 'relayer', 'npm', ['test'])];
  if (!args.has('--skip-rust')) for (const c of CONTRACTS) rows.push(run(`contract ${c}`, `contracts/${c}`, 'cargo', ['test', '--lib']));
  const dist = dirSize(join(ROOT, 'game/dist'));
  const sha = (() => { try { return execSync('git rev-parse --short HEAD', { cwd: ROOT, encoding: 'utf8' }).trim(); } catch { return 'unknown'; } })();
  const date = new Date().toISOString().slice(0, 10);
  const pad = (s, n) => String(s).padEnd(n);
  console.log(`\n${pad('suite', 26)}${pad('pass', 7)}${pad('fail', 7)}status`);
  for (const r of rows) console.log(`${pad(r.name, 26)}${pad(r.pass, 7)}${pad(r.fail == null ? '?' : r.fail, 7)}${r.ok ? 'ok' : 'FAILED'}`);
  if (dist != null) console.log(`game/dist: ${(dist / 1e6).toFixed(0)} MB`);
  const allOk = rows.every((r) => r.ok);
  if (args.has('--write')) {
    const json = { date, commit: sha, suites: rows.map(({ name, command, pass, fail, ok }) => ({ name, command, pass, fail, ok })), distBytes: dist };
    writeFileSync(join(ROOT, 'docs/stats.json'), JSON.stringify(json, null, 2) + '\n');
    const md = [`# Numbers`, '', `Generated by \`node scripts/stats.mjs --write\` on ${date} at commit \`${sha}\`. Every count in the README comes from this file; rerun it rather than editing numbers by hand.`, '',
      '| Suite | Command | Pass | Fail |', '|---|---|---:|---:|',
      ...rows.map((r) => `| ${r.name} | \`${r.command}\` | ${r.pass} | ${r.fail == null ? '?' : r.fail} |`),
      '', dist != null ? `Production build \`game/dist\`: ${(dist / 1e6).toFixed(0)} MB (\`cd game && npm run build\`).` : 'Production build not measured (run `cd game && npm run build` first).', ''].join('\n');
    writeFileSync(join(ROOT, 'docs/STATS.md'), md);
    console.log('wrote docs/STATS.md and docs/stats.json');
  }
  process.exit(allOk ? 0 : 1);
}
