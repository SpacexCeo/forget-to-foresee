#!/usr/bin/env node
// The build window from git alone (C12): commit count, first and last commit dates, commits before 2026-11-01 and
// before 2026-10-19, whether the `pre-hackathon` tag is the empty root commit, and the files changed since it.
//   node scripts/window-facts.mjs           prints the table
//   node scripts/window-facts.mjs --write   also writes docs/window.md
// Read-only on git. Exit 1 when git is not available or the clone is shallow (the counts would be wrong).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const run = (cwd, args) => execFileSync('git', ['-c', 'safe.directory=*', ...args], { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();

/** The facts for the repository at `cwd` (HEAD). */
export function windowFacts(cwd = process.cwd(), ref = 'HEAD') {
  const shallow = run(cwd, ['rev-parse', '--is-shallow-repository']) === 'true';
  const dates = run(cwd, ['log', '--format=%aI', ref]).split('\n').filter(Boolean);
  const count = (before) => Number(run(cwd, ['rev-list', '--count', `--before=${before}`, ref]));
  const root = run(cwd, ['rev-list', '--max-parents=0', ref]).split('\n')[0];
  let tag = null, files = null;
  try { tag = run(cwd, ['rev-parse', 'pre-hackathon^{commit}']); } catch { tag = null; }
  if (tag) { try { files = run(cwd, ['diff', '--name-only', tag, ref]).split('\n').filter(Boolean).length; } catch { files = null; } }
  let rootEmpty = null; try { rootEmpty = run(cwd, ['ls-tree', '-r', '--name-only', root]).split('\n').filter(Boolean).length <= 1; } catch { rootEmpty = null; } // at most a placeholder file
  return { shallow, commits: dates.length, first: dates[dates.length - 1] || null, last: dates[0] || null, before1Nov: count('2026-11-01T00:00:00+02:00'), before19Oct: count('2026-10-19T00:00:00+03:00'), root, preHackathon: tag, tagIsRoot: tag === root, rootEmpty, filesSinceTag: files };
}

export function windowMarkdown(f, head) {
  return `# The build window (generated)

Generated by \`node scripts/window-facts.mjs --write\` from git alone, at \`${head}\`. Do not edit by hand.

| Fact | Value | Command |
|---|---|---|
| Commits | ${f.commits} | \`git rev-list --count HEAD\` |
| First commit | ${f.first} | \`git log --reverse --format=%aI \\| head -1\` |
| Last commit | ${f.last} | \`git log -1 --format=%aI\` |
| Commits before 1 Nov 2026 | ${f.before1Nov} | \`git rev-list --count --before=2026-11-01 HEAD\` |
| Commits before 19 Oct 2026 | ${f.before19Oct} | \`git rev-list --count --before=2026-10-19 HEAD\` |
| \`pre-hackathon\` tag | ${f.preHackathon ? (f.tagIsRoot ? 'the root commit' : f.preHackathon) : 'missing'}${f.rootEmpty ? ' (an empty repository)' : ''} | \`git rev-parse pre-hackathon\`, \`git rev-list --max-parents=0 HEAD\` |
| Files changed since \`pre-hackathon\` | ${f.filesSinceTag ?? 'n/a'} | \`git diff --name-only pre-hackathon HEAD \\| wc -l\` |

The organizers' Q-001 counts the window from 19 Oct; the hackathon facts table says 1 Nov; the first commit here is ${(f.first || '').slice(0, 10)}, so both readings give the same answer.
The \`hackathon-submission\` tag (and the compare link \`pre-hackathon...hackathon-submission\`) exists only once the owner pushes it.
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  let f; try { f = windowFacts(); } catch { console.error('git is not available here'); process.exit(1); }
  if (f.shallow) { console.error('shallow clone: run `git fetch --unshallow --filter=blob:none` first (the counts would be wrong)'); process.exit(1); }
  console.table({ commits: f.commits, first: f.first, last: f.last, before_1_nov: f.before1Nov, before_19_oct: f.before19Oct, pre_hackathon_is_root: f.tagIsRoot, files_since_tag: f.filesSinceTag });
  if (process.argv.includes('--write')) { writeFileSync(new URL('../docs/window.md', import.meta.url), windowMarkdown(f, run(process.cwd(), ['rev-parse', '--short', 'HEAD']))); console.log('wrote docs/window.md'); }
}
